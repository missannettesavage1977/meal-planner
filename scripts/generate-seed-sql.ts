/**
 * Generates supabase/seed.sql from the TypeScript catalogue, recipes and demo
 * prices, so the database and the offline app share one source of truth.
 *
 *   npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { INGREDIENTS } from "../src/lib/data/ingredients";
import { SEED_RECIPES } from "../src/lib/data/recipes";
import { SUPERMARKETS, SUPERMARKET_LABELS } from "../src/lib/domain/types";
import { demoProducts } from "../src/lib/pricing/demoProvider";

export function buildSeedSql(): string {
  const q = (v: unknown): string => {
    if (v === null || v === undefined) return "null";
    if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
    if (typeof v === "boolean") return v ? "true" : "false";
    if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
    return `'${String(v).replace(/'/g, "''")}'`;
  };
  const out: string[] = ["-- Generated by scripts/generate-seed-sql.ts – do not edit by hand.", "begin;"];

  out.push(...SUPERMARKETS.map((s) => `insert into public.supermarkets (id, name) values (${q(s)}, ${q(SUPERMARKET_LABELS[s])}) on conflict (id) do update set name = excluded.name;`));

  for (const i of INGREDIENTS) {
    out.push(
      `insert into public.ingredients (id, name, plural, category, base_unit, item_label, grams_per_item, density_g_per_ml, diet_level, shelf_life_days, is_staple, protein, note) values (${[
        i.id, i.name, i.plural, i.category, i.baseUnit, i.itemLabel, i.gramsPerItem, i.density, i.diet, i.shelfLifeDays, Boolean(i.staple), i.protein, i.note,
      ].map(q).join(", ")}) on conflict (id) do nothing;`,
    );
    for (const a of new Set(i.aliases)) out.push(`insert into public.ingredient_aliases values (${q(i.id)}, ${q(a)}) on conflict do nothing;`);
    for (const [u, n] of Object.entries(i.customUnits ?? {})) out.push(`insert into public.ingredient_units values (${q(i.id)}, ${q(u)}, ${q(n)}) on conflict do nothing;`);
    for (const a of i.allergens) out.push(`insert into public.ingredient_allergens values (${q(i.id)}, ${q(a)}, false) on conflict do nothing;`);
    for (const a of i.mayContain ?? []) if (!i.allergens.includes(a)) out.push(`insert into public.ingredient_allergens values (${q(i.id)}, ${q(a)}, true) on conflict do nothing;`);
  }

  for (const r of SEED_RECIPES) {
    out.push(
      `insert into public.recipes (id, owner_id, name, description, cuisine, meal_types, servings, prep_mins, cook_mins, storage, keeps_days, freezable, tags, equipment, difficulty, emoji, hue, source) values (${[
        r.id, null, r.name, r.description, r.cuisine,
      ].map(q).join(", ")}, array[${r.mealTypes.map(q).join(", ")}]::public.meal_slot[], ${[r.servings, r.prepMins, r.cookMins, r.storage, r.keepsDays, r.freezable, r.tags, r.equipment, r.difficulty, r.emoji, r.hue].map(q).join(", ")}, 'original') on conflict (id) do nothing;`,
    );
    r.ingredients.forEach((ing, idx) =>
      out.push(`insert into public.recipe_ingredients (recipe_id, position, ingredient_id, name, quantity, unit, note, optional) values (${[r.id, idx, ing.ingredientId, ing.name, ing.quantity, ing.unit, ing.note, Boolean(ing.optional)].map(q).join(", ")}) on conflict (recipe_id, position) do nothing;`),
    );
    r.steps.forEach((s, idx) => out.push(`insert into public.recipe_steps values (${q(r.id)}, ${idx}, ${q(s)}) on conflict do nothing;`));
    out.push(`delete from public.recipe_substitutions where recipe_id = ${q(r.id)};`);
    for (const sub of r.substitutions) {
      sub.alternatives.forEach((alt, idx) =>
        out.push(`insert into public.recipe_substitutions (recipe_id, ingredient_id, position, alt_ingredient_id, alt_name, ratio, note) values (${[r.id, sub.ingredientId, idx, alt.ingredientId, alt.name, alt.ratio, alt.note].map(q).join(", ")});`),
      );
    }
  }

  for (const p of demoProducts()) {
    out.push(
      `insert into public.products (id, owner_id, supermarket_id, ingredient_id, name, brand, own_brand, pack_size, pack_label) values (${[p.id, null, p.supermarket, p.ingredientId, p.name, p.brand, p.ownBrand, p.packSize, p.packLabel].map(q).join(", ")}) on conflict (id) do nothing;`,
      `insert into public.price_observations (product_id, owner_id, price_pence, observed_on, source, confidence) values (${q(p.id)}, null, ${p.pricePence}, null, 'demo', 'low');`,
    );
  }
  out.push("commit;", "");
  return out.join("\n");
}

if (process.argv[1]?.includes("generate-seed-sql")) {
  const sql = buildSeedSql();
  writeFileSync("supabase/seed.sql", sql);
  console.log(`Wrote supabase/seed.sql (${sql.split("\n").length} lines)`);
}
